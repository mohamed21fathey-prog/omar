// بناء البرومبت النهائي لكل فيديو — الصوت العربي أول أول البرومبت
// (الموديلات بتوزن بداية البرومبت أكثر من نهايته — هنا كانت المشكلة
// قبل كده: التوجيه كان في الآخر فالموديل يتجاهله ويطلع لغة غريبة)
// 1) الصوت: عربي فصحى إلزامي في أول سطر + جملة نطق عربية فعلية
// 2) عدم التكرار: توقيع توليد فريد لكل محاولة يجبر المزود على مشهد
//    جديد تمامًا مهما تكررت الفكرة (لا فيديو متكرر بأي حال)
// ============================================================
export function arabicVideoPrompt(script: string, context: string): string {
  const nonce = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
  return [
    "🔊 قاعدة الصوت الأولى والأهم — لا تخالفها أبدًا: كل الصوت في الفيديو باللغة العربية الفصحى المبسطة المناسبة للأطفال، بصوت كرتوني دافئ واضح. ممنوع منعًا باتًا أي كلمة إنجليزية أو فرنسية أو بأي لغة أخرى غير العربية، وممنوع لغة عشوائية غير مفهومة.",
    "🎙️ التعليق الصوتي: الراوي ينطق بالعربية الفصحى جملة أو جملتين قصيرتين تناسبان حدث المشهد (مثل: «في يوم مشمس جميل، ذهب عمر إلى الحديقة…») — عربي فقط.",
    "",
    "وصف المشهد:",
    script.trim(),
    "",
    "🔊 تذكير صوتي حاسم: الصوت عربي فصحى مبسط فقط — لا كلام أجنبي ولا لغة غريبة ولا همهمة غير مفهومة.",
    `🔁 تنويع إلزامي (معرّف التوليد: ${nonce} | السياق: ${context}): هذا مشهد جديد تمامًا يُولَّد الآن لأول مرة — اجعله مختلفًا بصريًا وصوتيًا عن أي مشهد وُلّد من قبل لنفس الشخصية أو الفكرة: غيّر المكان والحركة وزوايا الكاميرا والإضاءة وتفاصيل البيئة والأحداث، ولا تكرر نفس اللقطة أو نفس الحدث أبدًا.`,
  ].join("\n");
}
